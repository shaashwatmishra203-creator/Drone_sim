#!/usr/bin/env python3
"""
gen_world.py — build the factory-like Gazebo world for the navigation mission.

Layout (metres, x forward from the launch base):

    BASE(0,0)  ->  slalom obstacle course  ->  ROOM(32,0) scan  ->  return to BASE

      y
      |   [rack]        [rack]                +---------------+
      |            [rack]        [rack]       |               |
    --+---O--------------------------------   |     ROOM      |  <- scan here
      |  base                                 |   12 x 12 m   |
      |        [pillar]      [pillar]         +---------------+
                                              (open on the -x face)

The course is deliberately tight enough to require real lateral movement but
wide enough to fly at low speed: 3.0 m gaps against a 0.5 m airframe.

Usage:  python3 tools/gen_world.py --out worlds/factory.sdf
"""

import argparse

